#!/usr/bin/env python3
"""Convert hand-authored PNG sprites (carol-courier/art/*.png, Aseprite-editable)
into a C header with per-sprite RGB565 palettes + index arrays.

Usage: python3 carol-courier/art/png2c.py   (run from the fm1-base root)
Reads the animations art/grump1.png..art/grump4.png, art/santa1.png..art/santa4.png
and the first two Frosty poses art/frosty1.png, art/frosty2.png; writes sprite_data.h.
Transparent pixels are index 0. Each animation's frames share one palette and are
stored back to back (frame f starts at PX + f*W*H), with a <NAME>_NFRAMES count.
"""
import pathlib
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent  # carol-courier/
# the single-frame sprites: the title banner, the fir, the music note and the
# sound page's icons (art/gen_art.py writes them; hand-edit them in Aseprite
# and the converter still uses your version)
SPRITES = ["title", "pine", "fir_small", "fir_tiny", "note", "clef",
           "icon_bells", "icon_choir", "icon_kazoo", "icon_piano", "icon_flute",
           "icon_sax", "icon_staff", "icon_midi"]
ANIMATED = {
    "GRUMP": ["grump1", "grump2", "grump3", "grump4"],
    "SANTA": ["santa1", "santa2", "santa3", "santa4"],
    "FROSTY": ["frosty1", "frosty2"],
}

def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

out = []
out.append("/* SPDX-License-Identifier: MPL-2.0")
out.append(" * Copyright (C) 2026 Charles Vestal */")
out.append("/* GENERATED by art/png2c.py from art/grump1.png..art/grump4.png, art/santa1.png..art/santa4.png, art/frosty1.png..art/frosty2.png.")
out.append(" * Hand-authored pixel art (see art/). Edit the PNGs in Aseprite, re-run the")
out.append(" * converter, and rebuild. Index 0 = transparent. */")
out.append("#pragma once")
out.append("#include <stdint.h>")
out.append("")

for name in SPRITES:
    img = Image.open(ROOT / "art" / f"{name}.png").convert("RGBA")
    w, h = img.size
    px = img.load()
    palette = [(0, 0, 0)]
    index_of = {}
    data = []
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            if a == 0:
                data.append(0)
            else:
                key = (r, g, b)
                if key not in index_of:
                    index_of[key] = len(palette)
                    palette.append(key)
                data.append(index_of[key])
    up = name.upper()
    out.append(f"#define {up}_W {w}")
    out.append(f"#define {up}_H {h}")
    out.append("")
    out.append(f"static const uint16_t {up}_PAL[] = {{")
    for i, (r, g, b) in enumerate(palette):
        out.append(f"    0x{rgb565(r, g, b):04X}u,  /* {i}: #{r:02X}{g:02X}{b:02X} */")
    out.append("};")
    out.append("")
    out.append(f"static const uint8_t {up}_PX[] = {{")
    for y in range(h):
        row = data[y * w:(y + 1) * w]
        out.append("    " + ",".join(str(v) for v in row) + ",")
    out.append("};")
    out.append("")
    print(f"{name}: {w}x{h}, {len(palette)} palette entries")

def emit_animation(up, filenames):
    """Append one multi-frame sprite: shared palette, frames back to back."""
    imgs = [Image.open(ROOT / "art" / f"{n}.png").convert("RGBA") for n in filenames]
    w, h = imgs[0].size
    assert all(g.size == (w, h) for g in imgs), f"{up} frames must share dimensions"
    pal = [(0, 0, 0)]
    idx = {}
    data = []
    for g in imgs:
        px = g.load()
        for y in range(h):
            for x in range(w):
                r, g2, b, a = px[x, y]
                if a == 0:
                    data.append(0)
                else:
                    key = (r, g2, b)
                    if key not in idx:
                        idx[key] = len(pal)
                        pal.append(key)
                    data.append(idx[key])
    assert len(pal) <= 256, f"{up} palette too large: {len(pal)} entries"
    out.append(f"#define {up}_W {w}")
    out.append(f"#define {up}_H {h}")
    out.append(f"#define {up}_NFRAMES {len(imgs)}")
    out.append("")
    out.append(f"static const uint16_t {up}_PAL[] = {{")
    for i, (r, g2, b) in enumerate(pal):
        out.append("    0x%04Xu,  /* %d: #%02X%02X%02X */" % (rgb565(r, g2, b), i, r, g2, b))
    out.append("};")
    out.append("")
    out.append(f"static const uint8_t {up}_PX[] = {{")
    for f in range(len(imgs)):
        off = f * w * h
        for y in range(h):
            row = data[off + y * w:off + (y + 1) * w]
            out.append("    " + ",".join(str(v) for v in row) + ",")
    out.append("};")
    out.append("")
    print(f"{up.lower()}: {w}x{h} x{len(imgs)} frames, {len(pal)} palette entries")

for _up, _files in ANIMATED.items():
    emit_animation(_up, _files)

(ROOT / "sprite_data.h").write_text("\n".join(out))
print("wrote sprite_data.h")
