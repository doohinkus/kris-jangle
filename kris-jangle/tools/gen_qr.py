"""Generate the QR codes the badge screen shows: one per carol and level.

The FM-1 has no QR encoder, so the bitmaps are made here, at build time, and
committed as a C header (like sprite_data.h, which art/png2c.py makes). The
page's address is in the QR, with the carol and the level as parameters, so
scanning it opens the page on the phone already knowing what was played.

The QR code itself is made by Project Nayuki's generator library (MIT), kept
beside this script as qrcodegen.py; see README.md and fm1.toml's credits.

Usage: python3 tools/gen_qr.py          (from the app's directory)
Writes: qr_data.h
       python3 tools/gen_qr.py --check  checks that qr_data.h is up to date
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import qrcodegen  # noqa: E402

BASE_URL = "https://doohinkus.github.io/kris-jangle/sound/"
CAROLS = 4                                  # the carols in the game
LEVELS = 11                                 # the levels of a carol
VERSION = 4                                 # 33 modules: the shortest that holds the address
ECC = qrcodegen.QrCode.Ecc.MEDIUM


def url_for(carol, level):
    """the page's address for a carol and a level"""
    return f"{BASE_URL}?c={carol}&l={level}"


def bitmap(url):
    """the QR code of a text as a list of rows of True/False (a module is dark)"""
    qr = qrcodegen.QrCode.encode_segments(
        [qrcodegen.QrSegment.make_bytes(url.encode("utf-8"))],
        ECC, minversion=VERSION, maxversion=VERSION)
    size = qr.get_size()
    return [[qr.get_module(x, y) for x in range(size)] for y in range(size)]


def pack(rows):
    """the modules as bits, row by row, least significant bit first"""
    bits = []
    for row in rows:
        for dark in row:
            bits.append(1 if dark else 0)
    out = bytearray((len(bits) + 7) // 8)
    for i, b in enumerate(bits):
        if b:
            out[i >> 3] |= 1 << (i & 7)
    return bytes(out)


def build():
    """the header's text, and the variants it holds"""
    variants = []
    for carol in range(CAROLS):
        for level in range(1, LEVELS + 1):
            url = url_for(carol, level)
            rows = bitmap(url)
            variants.append((carol, level, url, rows))

    modules = len(variants[0][3])
    for carol, level, url, rows in variants:
        if len(rows) != modules:
            raise SystemExit(f"c{carol} l{level}: {len(rows)} modules, not {modules}")
        if len(url) > 62:
            raise SystemExit(f"c{carol} l{level}: the address is {len(url)} characters, too long for version {VERSION}")

    nbytes = (modules * modules + 7) // 8
    out = []
    out.append("/* SPDX-License-Identifier: MPL-2.0")
    out.append(" * Copyright (C) 2026 Charles Vestal */")
    out.append("/* GENERATED by tools/gen_qr.py from Project Nayuki's QR generator (MIT, tools/qrcodegen.py).")
    out.append(" * One code per carol and level: the badge screen shows the one for the level just")
    out.append(" * cleared. The address carries the carol and the level, so the phone's page knows what")
    out.append(" * was played. Edit the script (the address, the carols, the levels) and re-run it. */")
    out.append("#pragma once")
    out.append("#include <stdint.h>")
    out.append("")
    out.append(f"#define QR_MODULES {modules}          /* a side, in modules */")
    out.append(f"#define QR_CAROLS {CAROLS}")
    out.append(f"#define QR_LEVELS {LEVELS}")
    out.append(f"#define QR_BYTES {(modules * modules + 7) // 8}      /* the modules of one code, packed */")
    out.append(f"#define QR_VARIANTS {len(variants)}")
    out.append("")
    out.append("/* One code per variant: carol * QR_LEVELS + (level - 1). A module is a bit, row by row,")
    out.append(" * least significant bit first: module (x, y) is bit y * QR_MODULES + x. */")
    out.append(f"static const uint8_t QR_BITS[QR_VARIANTS][QR_BYTES] = {{")
    for carol, level, url, rows in variants:
        data = pack(rows)
        hexs = ", ".join(f"0x{b:02X}u" for b in data)
        out.append(f"    {{ {hexs} }},  /* c{carol} l{level}: {url} */")
    out.append("};")
    out.append("")
    return "\n".join(out), variants, modules, nbytes


def main():
    app = pathlib.Path(__file__).resolve().parents[1]
    text, variants, modules, nbytes = build()
    if "--check" in sys.argv:
        have = (app / "qr_data.h").read_text(encoding="utf-8")
        if have != text:
            raise SystemExit("qr_data.h is not up to date: run python3 tools/gen_qr.py")
        print(f"qr_data.h is up to date: {len(variants)} codes, {modules} modules each")
        return
    (app / "qr_data.h").write_text(text, encoding="utf-8")
    print(f"qr_data.h: {len(variants)} codes, {modules} modules each ({modules * modules} bits, {nbytes} B a code), "
          f"{len(variants) * nbytes} B in all")
    longest = max(len(u) for _, _, u, _ in variants)
    print(f"the longest address is {longest} characters")


if __name__ == "__main__":
    main()
